#!/usr/bin/env python3
"""Write docs/original-spec/BUGS-COVERAGE.md from BUGS.md, the test sources and a reasons file.

Every bug ID in BUGS.md gets the `doesNotReproduce<AREA><NN>_...` tests found in src/test/java, or a reason
from docs/original-spec/bug-reasons.json (code not ported, feature dropped or deferred, with the decision that
says so). An ID with neither is listed as MISSING, so a gap in coverage is visible.

BUGS.md format (see docs/templates/bug-register.md): `## <severity>` headings, each followed by a table whose
rows start `| AREA-NN | <also> | ...`. A heading named "Not bugs" marks checked-and-dismissed rows.

bug-reasons.json maps an ID to [status, text], for example:
    {"CORE-18": ["cannot occur", "The teleporter is not ported (decision 0003)"]}
Statuses are free text; "cannot occur", "kept" and "deferred" are conventional.

Usage, from the repository root:
    python3 -I tools/bugs-coverage/generate.py [root]
"""
import json
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else '.'
bugs = open(root + '/docs/original-spec/BUGS.md').read().splitlines()
try:
    reasons = json.load(open(root + '/docs/original-spec/bug-reasons.json'))
except FileNotFoundError:
    reasons = {}

tests = {}
for dirpath, _, names in os.walk(root + '/src/test/java'):
    for n in names:
        if not n.endswith('.java'):
            continue
        for m in re.finditer(r'void (doesNotReproduce([A-Z]+)(\d+)_\w+)\(', open(os.path.join(dirpath, n)).read()):
            key = m.group(2) + '-' + m.group(3)
            tests.setdefault(key, []).append(n[:-5] + '#' + m.group(1))

rows = []
severity = None
counts = {}
for line in bugs:
    m = re.match(r'^## (\w[\w ]*)$', line)
    if m:
        severity = m.group(1).lower()
        continue
    m = re.match(r'^\| ([A-Z]+-\d+) \| ([^|]*)\|', line)
    if not m:
        continue
    bug, also = m.group(1), m.group(2).strip()
    if severity == 'not bugs':
        status, what = 'not a bug', 'Checked and not a bug ([BUGS.md](BUGS.md#not-bugs)); no test needed'
    elif bug in tests:
        status, what = 'tested', '<br>'.join('`' + t + '`' for t in sorted(tests[bug]))
    elif bug in reasons:
        status, what = reasons[bug]
    else:
        status, what = 'MISSING', ''
    counts[status] = counts.get(status, 0) + 1
    rows.append('| %s | %s | %s | %s | %s |' % (bug, also, severity, status, what))

out = ['# Bug coverage', '',
       '<!-- Generated by tools/bugs-coverage/generate.py from BUGS.md, the test sources and bug-reasons.json; rerun it when a bug gets a test or a reason. -->',
       '',
       'Every ID in [BUGS.md](BUGS.md) and how this mod keeps it out: a regression test named `doesNotReproduce<ID>_...`, '
       'or the reason the bug cannot occur here, with the decision that says so. Aliases in **Also** are the same bug '
       'under another area\'s ID and share the row.',
       '',
       '| Status | IDs |', '|---|---|']
for k in sorted(counts, key=lambda k: (k == 'MISSING', k)):
    out.append('| %s | %d |' % (k, counts[k]))
out += ['',
        '- **tested**: a `doesNotReproduce` test proves the bug does not come back.',
        '- **MISSING**: neither a test nor a reason; fix this before calling the area done.',
        '',
        '| ID | Also | Severity | Status | Test, or why it cannot occur |',
        '|---|---|---|---|---|'] + rows
open(root + '/docs/original-spec/BUGS-COVERAGE.md', 'w').write('\n'.join(out) + '\n')
print(counts)
